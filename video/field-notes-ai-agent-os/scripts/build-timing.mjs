import fs from "node:fs";
import path from "node:path";

/**
 * Build src/timing.ts from the measured narration lengths.
 * Scene length comes from the audio, never from a guess.
 */
const GAP = 12;
const TAIL = 26;
const LABELS = {
  hook: "THE QUESTION",
  answer: "THE CORE",
  foundations: "FOUNDATIONS",
  pillars: "FOUR PILLARS",
  agents: "PILLAR 3 · AGENTS",
  skills: "PILLAR 2 · SKILLS",
  guardrails: "GUARDRAILS",
  outro: "AUTONOMY",
};

const plan = JSON.parse(fs.readFileSync("plan.json", "utf8"));
const durations = JSON.parse(fs.readFileSync("public/content/ai-os/audio/durations.json", "utf8"));

let cursor = 0;
const scenes = plan.map((p, i) => {
  const measured = durations[p.scene];
  if (!measured) throw new Error(`no measured duration for ${p.scene}`);
  const isLast = i === plan.length - 1;
  const duration = measured + GAP + (isLast ? TAIL : 0);
  const scene = { id: p.scene, label: LABELS[p.scene] ?? p.scene.toUpperCase(), start: cursor, duration, narration: measured };
  cursor += duration;
  return scene;
});

// One breath of air between the last line and the end card.
const END_CARD_FROM = cursor + 4;
const TOTAL = END_CARD_FROM + 102;

const out = `// Generated by scripts/build-timing.mjs. Do not hand-edit.
export type SceneTiming = { id: string; label: string; start: number; duration: number; narration: number };
export const SCENES: SceneTiming[] = ${JSON.stringify(scenes, null, 2)};
export const END_CARD_FROM = ${END_CARD_FROM};
export const TOTAL = ${TOTAL};
`;

fs.writeFileSync("src/timing.ts", out);

// whisper needs the absolute frame each scene's narration starts on.
fs.writeFileSync(
  "public/content/ai-os/scenes.json",
  JSON.stringify(
    scenes.map((s) => ({ scene: s.id, startFrame: s.start })),
    null,
    2
  )
);
console.log(scenes.map((s) => `${s.id.padEnd(12)} start ${String(s.start).padStart(5)}  ${s.duration}f`).join("\n"));
console.log(`end card from ${END_CARD_FROM}, total ${TOTAL} frames (${(TOTAL / 30).toFixed(1)}s)`);
