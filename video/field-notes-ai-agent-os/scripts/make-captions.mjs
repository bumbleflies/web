/**
 * make-captions.mjs — derive caption tokens from the voiceover audio.
 *
 * Uses whisper.cpp through @remotion/install-whisper-cpp, so timings come from
 * the audio that actually plays. Captions cannot drift from narration because
 * nobody types a timestamp.
 *
 * Usage:
 *   node make-captions.mjs --scenes scenes.json --audio-dir public/content/<project>/audio \
 *                          --out-src src/caption-tokens.ts
 *
 * scenes.json:
 *   [{ "scene": "earth", "startFrame": 15 }, ...]
 *
 * Expects <audio-dir>/vo-<scene>-16k.wav (16 kHz mono). Create with:
 *   ffmpeg -i vo-earth.wav -ar 16000 -ac 1 -c:a pcm_s16le vo-earth-16k.wav
 */
import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import {
  installWhisperCpp,
  downloadWhisperModel,
  transcribe,
  toCaptions,
} from "@remotion/install-whisper-cpp";

const FPS = 30;
const WHISPER_VERSION = "1.5.5";
const MODEL = "base.en";

function parseArgs() {
  const a = process.argv.slice(2);
  const get = (flag, fallback) => {
    const i = a.indexOf(flag);
    return i >= 0 ? a[i + 1] : fallback;
  };
  return {
    scenes: get("--scenes"),
    audioDir: get("--audio-dir"),
    outSrc: get("--out-src", "src/caption-tokens.ts"),
    whisperPath: get("--whisper-path", "whisper.cpp"),
    model: get("--model", MODEL),
  };
}

async function ensureWhisper(whisperPath, model) {
  if (!fs.existsSync(path.join(whisperPath, "main"))) {
    console.log(`Installing whisper.cpp ${WHISPER_VERSION}`);
    await installWhisperCpp({ to: whisperPath, version: WHISPER_VERSION });
  }
  await downloadWhisperModel({ model, folder: whisperPath });
}

/**
 * whisper.cpp marks a new word with a leading space and splits punctuation and
 * thousands separators into their own tokens. A token starting with a space
 * opens a word; anything else continues it, so "3" + "," + "000" -> "3,000"
 * and "Earth" + "." -> "Earth.".
 */
function mergeWords(captions, startFrame) {
  const merged = [];
  for (const c of captions) {
    if (c.text.trim().length === 0) continue;
    const prev = merged[merged.length - 1];
    if (c.text.startsWith(" ") || !prev) {
      merged.push({
        text: c.text,
        from: startFrame + Math.round((c.startMs / 1000) * FPS),
        to: startFrame + Math.round((c.endMs / 1000) * FPS),
        confidence: c.confidence ?? null,
      });
    } else {
      prev.text += c.text.trim();
      prev.to = startFrame + Math.round((c.endMs / 1000) * FPS);
      if (prev.confidence != null && c.confidence != null) {
        prev.confidence = Math.min(prev.confidence, c.confidence);
      }
    }
  }
  return merged;
}

async function main() {
  const args = parseArgs();
  if (!args.scenes || !args.audioDir) {
    console.error("need --scenes <json> and --audio-dir <dir>");
    process.exit(2);
  }

  await ensureWhisper(args.whisperPath, args.model);

  const scenes = JSON.parse(fs.readFileSync(args.scenes, "utf8"));
  const tokens = [];

  for (const { scene, startFrame } of scenes) {
    const inputPath = path.join(args.audioDir, `vo-${scene}-16k.wav`);
    if (!fs.existsSync(inputPath)) {
      console.warn(`skip ${scene}: ${inputPath} not found`);
      continue;
    }

    const output = await transcribe({
      model: args.model,
      whisperPath: args.whisperPath,
      whisperCppVersion: WHISPER_VERSION,
      inputPath,
      tokenLevelTimestamps: true,
      tokenTimestamps: true,
      printOutput: false,
    });

    const { captions } = toCaptions({ whisperCppOutput: output });
    const words = mergeWords(captions, startFrame);
    tokens.push(...words);
    console.log(`${scene.padEnd(12)} ${captions.length} raw -> ${words.length} words`);
  }

  // Frames are the single source of truth; milliseconds derive from them so no
  // consumer can mix a scene-relative time with an absolute one.
  const lines = [
    "// Generated by make-captions.mjs from the voiceover audio. Do not hand-edit.",
    "export type Token = { text: string; from: number; to: number; fromMs: number; toMs: number; confidence: number | null };",
    "",
    "export const CAPTION_TOKENS: Token[] = [",
  ];
  for (const t of tokens) {
    const fromMs = Math.round((t.from / FPS) * 1000);
    const toMs = Math.round((t.to / FPS) * 1000);
    lines.push(
      `  { text: ${JSON.stringify(t.text)}, from: ${t.from}, to: ${t.to}, fromMs: ${fromMs}, toMs: ${toMs}, confidence: ${t.confidence} },`,
    );
  }
  lines.push("];");

  fs.mkdirSync(path.dirname(args.outSrc), { recursive: true });
  fs.writeFileSync(args.outSrc, lines.join("\n") + "\n");

  const low = tokens.filter((t) => (t.confidence ?? 1) < 0.8);
  console.log(`\n${tokens.length} tokens -> ${args.outSrc}`);
  console.log(`low-confidence (<0.8), ${low.length}: usually punctuation or short words`);
  for (const t of low) console.log(`   ${t.confidence.toFixed(3)}  ${JSON.stringify(t.text)}`);

  // Sanity check: tokens should advance through the timeline, not jump backwards.
  const regressions = tokens.filter((t, i) => i > 0 && t.from < tokens[i - 1].from);
  if (regressions.length) {
    console.warn(`\n${regressions.length} tokens start before their predecessor:`);
    for (const t of regressions) console.warn(`   f${t.from}  ${JSON.stringify(t.text)}`);
  }
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
